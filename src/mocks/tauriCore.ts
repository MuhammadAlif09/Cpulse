let isScanning = false;

export async function invoke<T = unknown>(cmd: string, args: any = {}): Promise<T> {
  console.log(`[Mock Tauri IPC] invoke("${cmd}")`, args);

  switch (cmd) {
    case "is_admin":
      return true as unknown as T;

    case "scan_junk": {
      isScanning = true;
      for (let p = 10; p <= 100; p += 10) {
        if (!isScanning) break;
        await new Promise((r) => setTimeout(r, 60));
        emit("scan_progress", p);
      }
      isScanning = false;
      return [...mockJunkList] as unknown as T;
    }

    case "cancel_scan":
      isScanning = false;
      return true as unknown as T;

    case "clean_junk": {
      const { categories = [] } = args;
      const count = categories.length || 1;
      for (let p = 10; p <= 100; p += 20) {
        await new Promise((r) => setTimeout(r, 80));
        emit("clean_progress", p);
      }
      return {
        bytes_freed: count * 450_000_000,
        files_cleaned: count * 180,
      } as unknown as T;
    }

    case "open_cleaner_audit_log":
      return "Opened cleaner_audit.log" as unknown as T;

    case "flush_dns":
      return "DNS cache flushed successfully" as unknown as T;

    case "clean_ram":
      return 1478492160 as unknown as T; // 1.4 GB freed

    case "apply_boost":
      return `Boost ${args.id || "applied"} applied successfully` as unknown as T;

    case "restore_boost":
      return `Restored default setting for ${args.id || "item"}` as unknown as T;

    case "set_power_plan":
      return `Power plan set to ${args.plan || "balanced"}` as unknown as T;

    case "toggle_context_menu":
      return `Context menu ${args.enable ? "enabled" : "disabled"}` as unknown as T;

    case "update_auto_clean":
      return `Auto-clean ${args.enable ? "scheduled" : "removed"}` as unknown as T;

    case "update_auto_update":
      return `Auto-update ${args.enable ? "enabled" : "disabled"}` as unknown as T;

    case "update_notifications":
      return `Notifications ${args.enable ? "enabled" : "disabled"}` as unknown as T;

    case "update_language":
      return `Language set to ${args.lang || "en"}` as unknown as T;

    case "get_startup_items":
      return [...mockStartupItems] as unknown as T;

    case "toggle_startup_item": {
      const { name, enable } = args;
      mockStartupItems = mockStartupItems.map((item) =>
        item.name === name ? { ...item, enabled: !!enable } : item
      );
      return `Toggled ${name}` as unknown as T;
    }

    case "add_startup_item": {
      const { name, path, isHkcu } = args;
      mockStartupItems.push({
        name,
        command: path,
        publisher: "Custom App",
        registry_path: isHkcu
          ? "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run"
          : "HKLM\\Software\\Microsoft\\Windows\\CurrentVersion\\Run",
        is_hkcu: !!isHkcu,
        enabled: true,
        impact: "Medium",
        delay: 1.0,
      });
      return `Added startup item ${name}` as unknown as T;
    }

    case "delete_startup_item": {
      const { name } = args;
      mockStartupItems = mockStartupItems.filter((i) => i.name !== name);
      return `Deleted startup item ${name}` as unknown as T;
    }

    case "scan_privacy":
      return {
        chrome_hist: { found: true, count: 1842, desc: "1,842 URLs found" },
        edge_hist: { found: true, count: 673, desc: "673 URLs found" },
        recent_files: { found: true, count: 128, desc: "128 entries" },
        clipboard: { found: true, count: 47, desc: "47 copied items" },
        search_hist: { found: true, count: 312, desc: "312 queries" },
        wifi_pass: { found: true, count: 9, desc: "9 networks stored" },
        cookies: { found: true, count: 4291, desc: "4,291 cookies" },
        run_hist: { found: false, count: 0, desc: "No run command entries" },
      } as unknown as T;

    case "sweep_privacy":
      return "Selected privacy traces swept successfully" as unknown as T;

    case "get_system_info":
      return {
        os_name: "Windows 11 Pro",
        os_version: "23H2 (22631.3880)",
        kernel: "10.0.22631",
        host_name: "DESKTOP-CPULSE",
      } as unknown as T;

    case "get_windows_key": {
      return {
        key: "",
        key_type: "Not Detected",
        edition: "Windows 11 Pro",
        is_valid: false,
      } as unknown as T;
    }

    case "get_diagnostics_reports":
      return mockDiagnosticsReports.map((r) => r.filename) as unknown as T;

    case "generate_diagnostics_report": {
      const dateStr = new Date().toISOString().slice(0, 10);
      const newFile = `report_${dateStr}_${Math.floor(Math.random() * 1000)}.txt`;
      const reportObj = {
        filename: newFile,
        date: new Date().toLocaleString(),
        content: `=== CPulse System Diagnostics Report ===
Generated: ${new Date().toLocaleString()}
Host Name: DESKTOP-CPULSE
OS Name: Windows 11 Pro
CPU: AMD Ryzen 7 7800X3D
Memory: 32 GB
Disks: C: Healthy
`,
      };
      mockDiagnosticsReports.unshift(reportObj);
      return newFile as unknown as T;
    }

    case "read_diagnostics_report": {
      const match = mockDiagnosticsReports.find((r) => r.filename === args.filename);
      if (!match) throw new Error("Report not found");
      return match.content as unknown as T;
    }

    case "export_diagnostics_report":
      return "Report exported successfully to Downloads folder." as unknown as T;

    default:
      console.error(`[Mock Tauri IPC Error] Unknown command: "${cmd}"`);
      throw new Error(`Command "${cmd}" is not registered in Tauri IPC backend.`);
  }
}
